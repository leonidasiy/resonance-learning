// @ts-check

import { generateServiceWorker } from "./build.mjs";

const stageMarker = "public/.resonance-stage";

if (Deno.args[0] === "stage") {
  try {
    await Deno.stat("public");
    await Deno.stat(stageMarker);
    await Deno.remove("public", { recursive: true });
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
    try {
      await Deno.stat("public");
      throw new Error("PublicDirectoryNotGenerated");
    } catch (cause) {
      if (!(cause instanceof Deno.errors.NotFound)) throw cause;
    }
  }
  await Deno.mkdir("public");
  await Deno.writeTextFile(stageMarker, "generated by scripts/next-static.mjs\n");
  await copyTree("dist", "public", "index.html");
} else if (Deno.args[0] === "publish") {
  await Deno.stat(stageMarker);
  await Deno.stat("out/index.html");
  await Deno.remove("out/.resonance-stage");
  const manifest = JSON.parse(await Deno.readTextFile("out/asset-manifest.json"));
  if (!Array.isArray(manifest) || !manifest.every((path) => typeof path === "string")) {
    throw new Error("LegacyAssetManifestInvalid");
  }
  const nextFiles = await listFiles("out/_next");
  await Deno.writeTextFile("out/asset-manifest.json", JSON.stringify([
    ...manifest,
    ...nextFiles.map((path) => `./${path.slice(4)}`),
  ]));
  await Deno.copyFile("service-worker.js", "out/service-worker.js");
  const worker = await generateServiceWorker("out");
  if (!worker.ok) throw new Error(worker.error.message);
  await Deno.remove("dist", { recursive: true });
  await Deno.rename("out", "dist");
  await Deno.remove("public", { recursive: true });
} else {
  throw new Error("Expected stage or publish");
}

/** @param {string} from @param {string} to @param {string | undefined} [excluded] */
async function copyTree(from, to, excluded) {
  for await (const entry of Deno.readDir(from)) {
    if (entry.name === excluded) continue;
    const source = `${from}/${entry.name}`;
    const destination = `${to}/${entry.name}`;
    if (entry.isDirectory) {
      await Deno.mkdir(destination);
      await copyTree(source, destination);
    } else if (entry.isFile) {
      await Deno.copyFile(source, destination);
    }
  }
}

/** @param {string} directory @returns {Promise<string[]>} */
async function listFiles(directory) {
  /** @type {string[]} */
  const files = [];
  for await (const entry of Deno.readDir(directory)) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory) files.push(...await listFiles(path));
    else if (entry.isFile) files.push(path);
  }
  return files;
}
